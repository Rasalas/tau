/** `drawable-port-xhdpi` → `drawable-port-night-xhdpi`: night sits after orientation. */
export function nightFolder(folder) {
  const parts = folder.split("-");
  const at = parts[1] === "port" || parts[1] === "land" ? 2 : 1;
  parts.splice(at, 0, "night");
  return parts.join("-");
}

// ------------------------------------------------------------------ Apple

const srgb = (hex) => "srgb:" + [1, 3, 5].map((i) => (parseInt(hex.slice(i, i + 2), 16) / 255).toFixed(5)).join(",") + ",1.00000";

function centreline(d) {
  const numbers = (text) => text.trim().split(/[\s,]+/u).map(Number);
  const points = [];
  let current;
  for (const [, command, args] of d.matchAll(/([MLC])([^MLC]*)/gu)) {
    const values = numbers(args);
    if (command === "M" || command === "L") {
      current = [values[0], values[1]];
      points.push(current);
      continue;
    }
    const [p0, p1, p2, p3] = [current, [values[0], values[1]], [values[2], values[3]], [values[4], values[5]]];
    for (let step = 1; step <= 64; step++) {
      const t = step / 64, u = 1 - t;
      points.push([0, 1].map((axis) => u ** 3 * p0[axis] + 3 * u * u * t * p1[axis] + 3 * u * t * t * p2[axis] + t ** 3 * p3[axis]));
    }
    current = p3;
  }
  return points;
}

const round2 = (value) => Math.round(value * 100) / 100;

/**
 * A round-capped stroke as a filled outline. Icon Composer colours a layer's shapes
 * by filling them, and actool's icns renderer fills an open stroke's inside too.
 */
export function strokeOutline(stroke, scale = 1, offset = [0, 0]) {
  const points = centreline(stroke.d).map(([x, y]) => [(x + offset[0]) * scale, (y + offset[1]) * scale]);
  const r = (stroke.width * scale) / 2;
  const normal = (index) => {
    const [a, b] = [points[Math.max(0, index - 1)], points[Math.min(points.length - 1, index + 1)]];
    const [dx, dy] = [b[0] - a[0], b[1] - a[1]];
    const length = Math.hypot(dx, dy);
    return [-dy / length, dx / length];
  };
  const side = (sign) => points.map((point, index) => {
    const [nx, ny] = normal(index);
    return `${round2(point[0] + sign * nx * r)} ${round2(point[1] + sign * ny * r)}`;
  });
  const left = side(1), right = side(-1).reverse();
  const arc = `A${round2(r)} ${round2(r)} 0 0 0 `;
  return `M${left[0]}L${left.slice(1).join("L")}${arc}${right[0]}L${right.slice(1).join("L")}${arc}${left[0]}Z`;
}

/**
 * The Icon Composer layer: the τ from the macOS-grid icon, scaled from Apple's 824 grid
 * to the document's 1024 canvas, as filled outlines in the given colour.
 */
export function iconComposerGlyph(iconLight, colour) {
  const paths = readStrokes(iconLight).map((stroke) => `<path d="${strokeOutline(stroke, 1024 / 824, [-100, -100])}" fill="${colour}"/>`);
  return svgRoot(1024, 1024, paths.join("\n"));
}

/** macOS 26's icon document (`.icon`); electron-builder compiles it with actool. */
export function iconComposerDocument() {
  const gradient = (top, bottom) => ({ "linear-gradient": [srgb(top), srgb(bottom)] });
  return JSON.stringify({
    "fill-specializations": [
      { value: gradient(COLOURS.plateTop, COLOURS.plateBottom) },
      { appearance: "dark", value: gradient(COLOURS.nightTop, COLOURS.nightBottom) },
    ],
    groups: [{
      layers: [{
        "image-name-specializations": [{ value: "tau.svg" }, { appearance: "dark", value: "tau-dark.svg" }],
        name: "tau",
      }],
      shadow: { kind: "neutral", opacity: 0.5 },
      translucency: { enabled: true, value: 0.5 },
    }],
    "supported-platforms": { squares: ["macOS"] },
  }, null, 2) + "\n";
}

const catalog = (images) => JSON.stringify({ images, info: { author: "xcode", version: 1 } }, null, 2) + "\n";

/** iOS 18 app icon: default, dark and tinted, each one 1024 image. */
export function iosAppIconContents() {
  const image = (filename, appearance) => ({
    ...(appearance ? { appearances: [{ appearance: "luminosity", value: appearance }] } : {}),
    filename, idiom: "universal", platform: "ios", size: "1024x1024",
  });
  return catalog([image("AppIcon-1024.png"), image("AppIcon-1024-dark.png", "dark"), image("AppIcon-1024-tinted.png", "tinted")]);
}

/** The launch storyboard's image: one 2732 picture per appearance, used at every scale. */
export function iosSplashContents() {
  const dark = [{ appearance: "luminosity", value: "dark" }];
  return catalog(["1x", "2x", "3x"].flatMap((scale) => [
    { filename: "splash.png", idiom: "universal", scale },
    { appearances: dark, filename: "splash-dark.png", idiom: "universal", scale },
  ]));
}

