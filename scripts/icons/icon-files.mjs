// What the icon generator writes, as text: the SVGs it rasterises and the files it
// writes as they are (Android vectors, the Icon Composer document, asset catalogs,
// the web manifest). Pure functions over the sources in assets/icon/, so a test
// can check the committed text files without rendering anything.

export const COLOURS = {
  plateTop: "#5c87d6",
  plateBottom: "#4670c0",
  paper: "#fbfaf8",
  blueDark: "#6b93e0",
  nightTop: "#232322",
  nightBottom: "#11110f",
  // K69's document surfaces; the splash screens sit on them.
  lightSurface: "#fbfaf8",
  darkSurface: "#1a1a19",
};

/** The τ's strokes in an SVG: every path with a stroke width. */
export function readStrokes(svg) {
  return [...svg.matchAll(/<path\b[^>]*>/gu)].flatMap(([tag]) => {
    const attribute = (name) => tag.match(new RegExp(`\\s${name}="([^"]*)"`, "u"))?.[1];
    const width = attribute("stroke-width");
    return width ? [{ d: attribute("d"), width: Number(width), colour: attribute("stroke") }] : [];
  });
}

/** Everything inside the root element except its title. */
export function svgBody(svg) {
  const start = svg.indexOf(">", svg.indexOf("<svg")) + 1;
  return svg.slice(start, svg.lastIndexOf("</svg>")).replace(/<title>[^<]*<\/title>/u, "").trim();
}

const svgRoot = (width, height, body, viewBox = `0 0 ${width} ${height}`) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="${viewBox}">\n${body}\n</svg>\n`;

const strokePaths = (strokes, colour, transform = "") => {
  const paths = strokes.map((stroke) =>
    `<path d="${stroke.d}" fill="none" stroke="${colour ?? stroke.colour}" stroke-width="${stroke.width}" stroke-linecap="round" stroke-linejoin="round"/>`).join("\n");
  return transform ? `<g transform="${transform}">\n${paths}\n</g>` : paths;
};

/** A 1024 source cut to a shape: `round` (Android's legacy round icon) or a rounded square. */
export function clippedSvg(source, shape) {
  const clip = shape === "round"
    ? `<circle cx="512" cy="512" r="469"/>`
    : `<rect x="43" y="43" width="938" height="938" rx="170"/>`;
  return svgRoot(1024, 1024, `<defs><clipPath id="shape">${clip}</clipPath></defs>\n<g clip-path="url(#shape)">\n${svgBody(source)}\n</g>`);
}

/** iOS 18's tinted icon: the full-bleed τ in white on black; the system tints the grey. */
export function tintedSvg(square) {
  return svgRoot(1024, 1024, `<rect width="1024" height="1024" fill="#000"/>\n${strokePaths(readStrokes(square), "#fff")}`);
}

/** A splash screen: the macOS-grid icon centred on a surface, a fifth of the short side. */
export function splashSvg(icon, width, height, surface) {
  const size = Math.round(Math.min(width, height) * 0.2);
  const x = Math.round((width - size) / 2), y = Math.round((height - size) / 2);
  return svgRoot(width, height,
    `<rect width="${width}" height="${height}" fill="${surface}"/>\n<svg x="${x}" y="${y}" width="${size}" height="${size}" viewBox="0 0 1024 1024">\n${svgBody(icon)}\n</svg>`);
}

// ------------------------------------------------------------------ Android

const ANDROID_NS = `xmlns:android="http://schemas.android.com/apk/res/android"`;
const argb = (hex) => `#FF${hex.slice(1).toUpperCase()}`;

function androidVector(paths, extraNs = "") {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/icons/generate.mjs from assets/icon/; edit the SVGs, not this file. -->
<vector ${ANDROID_NS}${extraNs}
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="1024"
    android:viewportHeight="1024">
${paths}
</vector>
`;
}

const androidStrokes = (strokes, colour) => strokes.map((stroke) => `    <path
        android:pathData="${stroke.d}"
        android:strokeColor="${argb(colour)}"
        android:strokeWidth="${stroke.width}"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />`).join("\n");

/** The adaptive icon's foreground: the τ inside the 66 dp safe circle. */
export function androidForeground(foregroundSvg) {
  return androidVector(androidStrokes(readStrokes(foregroundSvg), COLOURS.paper));
}

/** Android 13's themed icon: the same τ, one opaque colour; the launcher tints it. */
export function androidMonochrome(foregroundSvg) {
  return androidVector(androidStrokes(readStrokes(foregroundSvg), "#ffffff"));
}

/** The adaptive icon's background: the plate's gradient, as on the other platforms. */
export function androidBackground() {
  return androidVector(`    <path android:pathData="M0,0h1024v1024h-1024z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="0"
                android:startY="0"
                android:endX="0"
                android:endY="1024">
                <item android:offset="0" android:color="${argb(COLOURS.plateTop)}" />
                <item android:offset="1" android:color="${argb(COLOURS.plateBottom)}" />
            </gradient>
        </aapt:attr>
    </path>`, `\n    xmlns:aapt="http://schemas.android.com/aapt"`);
}

